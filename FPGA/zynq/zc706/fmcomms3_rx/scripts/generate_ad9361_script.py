#!/usr/bin/env python3
"""Compile an ADI GUI export to the existing ordered script-operation ABI.

No RF values are adapted here. Crystal/DCXO, masked writes, and ENSM entry
remain explicit board operations in ad_config.c. Unknown commands fail closed.
"""
import argparse
import hashlib
from pathlib import Path
import re


CALIBRATIONS = {
    "BBPLL": (0x05E, 0x80, 0x80),
    "RXCP": (0x244, 0x80, 0x80),
    "TXCP": (0x284, 0x80, 0x80),
    "RXFILTER": (0x016, 0x80, 0x00),
    "TXFILTER": (0x016, 0x40, 0x00),
    "BBDC": (0x016, 0x01, 0x00),
    "RFDC": (0x016, 0x02, 0x00),
    "TXQUAD": (0x016, 0x10, 0x00),
}


def parse_script(source):
    operations = []
    for line_number, raw in enumerate(source.decode("ascii").splitlines(), 1):
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        if line_number > 65535:
            raise ValueError("source line exceeds operation ABI")
        parts = line.split(None, 1)
        command = parts[0]
        argument = re.sub(r"\s+", "", parts[1]) if len(parts) == 2 else ""
        reg = timeout = value = mask = 0
        if command == "SPIWrite":
            match = re.fullmatch(r"([\da-fA-F]{1,3}),([\da-fA-F]{1,2})", argument)
            if not match:
                raise ValueError(f"line {line_number}: invalid SPIWrite")
            reg, value = (int(s, 16) for s in match.groups())
            if reg > 0x3FF:
                raise ValueError(f"line {line_number}: register out of range")
            opcode = 1
        elif command == "SPIRead":
            if not re.fullmatch(r"[\da-fA-F]{1,3}", argument):
                raise ValueError(f"line {line_number}: invalid SPIRead")
            reg, opcode = int(argument, 16), 2
            if reg > 0x3FF:
                raise ValueError(f"line {line_number}: register out of range")
        elif command == "WAIT":
            if not argument.isdecimal():
                raise ValueError(f"line {line_number}: invalid WAIT")
            timeout, opcode = int(argument), 3
        elif command == "WAIT_CALDONE":
            match = re.fullmatch(r"([A-Z]+),(\d+)", argument)
            if not match or match[1] not in CALIBRATIONS:
                raise ValueError(f"line {line_number}: unsupported calibration")
            reg, mask, value = CALIBRATIONS[match[1]]
            timeout, opcode = int(match[2]), 4
        elif command in ("RESET_DUT", "ReadPartNumber", "RESET_FPGA") and not argument:
            opcode = {"RESET_DUT": 5, "ReadPartNumber": 6, "RESET_FPGA": 7}[command]
        elif command == "BlockWrite" and argument == "2,6":
            reg, value, opcode = 2, 6, 8
        elif command == "REFCLK_Scale" and argument == "40.000000,1,2":
            opcode = 9
        else:
            raise ValueError(f"line {line_number}: unsupported command {line!r}")
        if not 0 <= timeout <= 65535:
            raise ValueError(f"line {line_number}: timeout exceeds operation ABI")
        operations.append((reg, timeout, line_number, opcode, value, mask))
    if not operations:
        raise ValueError("empty script")
    return operations


def render_header(source, symbol):
    if not re.fullmatch(r"[a-z][a-z0-9_]*", symbol):
        raise ValueError("invalid C symbol")
    operations = parse_script(source)
    upper = symbol.upper()
    digest = hashlib.sha256(source).hexdigest()
    lines = [
        f"/* Generated by scripts/generate_ad9361_script.py; source SHA256: {digest}",
        " * Preserves every operation and its source line. Board adaptations are in the executor.",
        " * Reuses the legacy script-operation ABI without modifying config915_data.h. */",
        f"#ifndef {upper}_DATA_H", f"#define {upper}_DATA_H",
        '#include "config915_data.h"',
        f'#define {upper}_SOURCE_SHA256 "{digest}"',
        f"static const config915_operation {symbol}_operations[] = {{",
    ]
    lines.extend(
        f"    {{0x{reg:03X}, {timeout}, {line}, {opcode}, 0x{value:02X}, 0x{mask:02X}}},"
        for reg, timeout, line, opcode, value, mask in operations
    )
    return "\n".join(lines + ["};", "#endif", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--symbol", default="config2p4")
    args = parser.parse_args()
    source = args.source.read_bytes()
    header = render_header(source, args.symbol)
    if not args.output.exists() or args.output.read_text() != header:
        args.output.write_text(header)
    print(f"Generated {args.output}: {len(parse_script(source))} operations")


if __name__ == "__main__":
    main()
